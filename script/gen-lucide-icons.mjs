#!/usr/bin/env node
// Regenerates plugin/ui/core/LucideIcons.h: one SVG string per Lucide icon
// the UI draws (Icons::draw parses each once into a Drawable). ICONS below
// is the set; add a name here, run the script, then use Icon::<Name>.
//
//   node script/gen-lucide-icons.mjs
//
// Needs Node and npm: the script installs the pinned lucide-react package
// into a temp directory (the icon node lists ship as ES modules there) and
// removes it afterwards. LUCIDE_VERSION is pinned so glyph shapes only
// change when someone bumps it on purpose.
//
// Each icon gets lucide's default attributes (24×24 viewBox, 2px round
// stroke, `currentColor` → white, tinted at draw time by Icons::draw).

import { execSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const LUCIDE_VERSION = '1.33.0';

const ICONS = [
  'ArrowLeft', 'ArrowLeftRight', 'ArrowRight', 'ArrowUpDown', 'Bluetooth', 'Bookmark',
  'Check', 'ChevronDown', 'ChevronLeft', 'ChevronRight', 'ChevronUp', 'Circle',
  'ClipboardPaste', 'Copy', 'Download', 'Equal', 'ExternalLink', 'File', 'FolderClosed',
  'Gauge', 'GripVertical', 'Info', 'Laptop', 'Link', 'ListFilter', 'LogIn', 'LogOut',
  'MidiPort', 'Pencil', 'Plus', 'PlusCircle', 'Power', 'Redo2', 'RotateCcw', 'Save',
  'Search', 'Settings', 'Share', 'ShieldAlert', 'Smartphone', 'Trash2', 'Undo2', 'Upload',
  'Volume2', 'WifiOff', 'X',
];

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'plugin/ui/core/LucideIcons.h');
const names = [...new Set(ICONS)].sort();

// Lucide's own toKebabCase: a letter→digit boundary also splits (Redo2 → redo-2).
const kebab = (s) =>
  s
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
    .replace(/([a-zA-Z])(\d)/g, '$1-$2')
    .toLowerCase();

const attrs = (o) =>
  Object.entries(o)
    .filter(([k]) => k !== 'key')
    .map(([k, v]) => ` ${k}="${v}"`)
    .join('');

const work = mkdtempSync(join(tmpdir(), 't3k-lucide-'));
try {
  execSync(`npm install --silent --no-audit --no-fund --prefix "${work}" lucide-react@${LUCIDE_VERSION}`, {
    stdio: 'inherit',
  });
  const lucideDir = join(work, 'node_modules/lucide-react/dist/esm/icons');

  // Alias modules (PlusCircle → circle-plus) only re-export the component;
  // follow the re-export to the module that owns the node list.
  const loadIconNode = async (file) => {
    const alias = readFileSync(file, 'utf8').match(/^export \{ default \} from '\.\/(.+)';$/m);
    if (alias) return loadIconNode(join(lucideDir, alias[1]));
    return (await import(pathToFileURL(file).href)).__iconNode;
  };

  const entries = [];
  for (const name of names) {
    const node = await loadIconNode(join(lucideDir, `${kebab(name)}.mjs`));
    const body = node.map(([tag, a]) => `<${tag}${attrs(a)}/>`).join('');
    const svg =
      `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="#ffffff" ` +
      `stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${body}</svg>`;
    entries.push({ name, svg });
  }

  const header = `// GENERATED by script/gen-lucide-icons.mjs from lucide-react ${LUCIDE_VERSION}; do not edit.
// The icon set is the script's ICONS list. Lucide is ISC licensed.
#pragma once

namespace t3k::ui {

enum class Icon {
${entries.map((e) => `  ${e.name},`).join('\n')}
};

inline constexpr int kIconCount = ${entries.length};

inline const char* lucideSvg(Icon icon) {
  switch (icon) {
${entries.map((e) => `    case Icon::${e.name}:\n      return R"svg(${e.svg})svg";`).join('\n')}
  }
  return "";
}

}  // namespace t3k::ui
`;

  writeFileSync(out, header);
  console.log(`wrote ${entries.length} icons to ${out}`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
